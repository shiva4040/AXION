import pytest
from axion.core.provider import MockProvider
from axion.orchestrator import CognitivePipeline, ResearchAnswer
from axion.pipeline.stage01_question import ScientificQuestionProcessor
from axion.pipeline.stage03_extraction import ScientificEvidenceExtractor
from axion.pipeline.types import (
    AcquiredChunk,
    AcquisitionPayload,
    ProvenancePointer,
    QuestionIntent,
    QuestionSpec,
    SubQuestion,
)


@pytest.mark.asyncio
async def test_stage01_decomposition_and_requirements():
    processor = ScientificQuestionProcessor(provider=MockProvider())
    query = "How does aerodynamic drag counteract the electrical power generated by a rooftop photovoltaic array at cruising velocity v = 120 km/h?"
    spec = await processor.process_question(query)

    assert isinstance(spec, QuestionSpec)
    assert len(spec.subquestions) >= 2
    assert len(spec.research_requirements) >= 1
    assert any(sq.id == "SQ-1" for sq in spec.subquestions)
    assert any(sq.id == "SQ-2" for sq in spec.subquestions)

    # Check dependency tracking
    if "SQ-3" in spec.subquestion_dependencies:
        deps = spec.subquestion_dependencies["SQ-3"]
        assert "SQ-1" in deps or "SQ-2" in deps


@pytest.mark.asyncio
async def test_stage03_evidence_extraction_with_subquestion_attribution():
    extractor = ScientificEvidenceExtractor()
    sq1 = SubQuestion(
        id="SQ-1",
        question="What are the governing equations for aerodynamic drag?",
        target_subject="aerodynamics:fluid",
        information_needed=["Drag force equation and drag coefficient"],
    )
    sq2 = SubQuestion(
        id="SQ-2",
        question="What is the electrical power generation equation for photovoltaic array?",
        target_subject="physics:photovoltaics",
        information_needed=["PV power formula with irradiance and area"],
        depends_on=["SQ-1"],
    )
    q_spec = QuestionSpec(
        raw_query="How does aerodynamic drag counteract PV power?",
        intent=QuestionIntent.ANALOGICAL_TRANSFER,
        subquestions=[sq1, sq2],
    )

    chunk = AcquiredChunk(
        chunk_id="chk-001",
        document_id="doc-aero-pv-01",
        page_number=1,
        source_title="Coupled Aerodynamic Photovoltaics",
        text_content="The aerodynamic drag force is F_drag = 0.5 * rho * v^2 * C_d * A under steady cruising conditions. Solar power is P_solar = G * A * eta.",
        provenance=ProvenancePointer(
            document_id="doc-aero-pv-01",
            chunk_id="chk-001",
            page_number=1,
            extracted_snippet="The aerodynamic drag force is F_drag = 0.5 * rho * v^2 * C_d * A",
        ),
    )

    payload = AcquisitionPayload(
        query_id=q_spec.query_id,
        retrieved_chunks=[chunk],
        sources_queried=["arXiv", "Crossref"],
        total_retrieved=1,
    )

    items = await extractor.extract_structured_evidence(payload, q_spec)
    assert len(items) >= 1

    # Verify that each item is mapped to relevant subquestions and has a relevance explanation
    for item in items:
        assert len(item.relevant_subquestion_ids) > 0
        assert len(item.relevance_explanation) > 0
        assert item.source_name == "Coupled Aerodynamic Photovoltaics"


@pytest.mark.asyncio
async def test_cognitive_pipeline_master_ask():
    pipeline = CognitivePipeline()
    query = "How does an electric motor convert electrical energy into mechanical torque?"
    answer = await pipeline.ask(query)

    assert isinstance(answer, ResearchAnswer)
    assert len(answer.direct_answer) > 0
    assert len(answer.important_points) > 0
    assert len(answer.how_it_works) > 0
    assert len(answer.final_takeaway) > 0
    assert len(answer.subquestions) >= 1
    assert len(answer.research_requirements) >= 1
    assert isinstance(answer.acquired_sources, list)
    assert isinstance(answer.extracted_evidence, list)
    assert answer.suggested_3d_scene == "electric_motor"
